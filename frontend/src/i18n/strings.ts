/**
 * Every word the interface says, in both languages it speaks.
 *
 * **Technical vocabulary is not translated.** Overdrive stays overdrive, a head
 * stays a head, a cabinet stays a cabinet -- and so do gain, threshold, attack,
 * release, ratio, mix, feedback, spillover, crossover, oversampling, impulse
 * response, preset, scene, channel, bypass and mute. These are the words the
 * gear itself uses and the words anyone reading a manual will meet; inventing
 * Indonesian for them would make the app *harder* to use, not friendlier. What
 * is translated is the connective tissue: what a block does, what a button
 * will do, what went wrong.
 *
 * Keys are namespaced by where they appear, so a string is easy to find from a
 * screenshot and hard to reuse somewhere it does not fit.
 */
